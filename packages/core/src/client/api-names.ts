export type ApiName<P extends Platform, K extends string> = `${P}.${K}` extends keyof typeof API_NAMES
  ? (typeof API_NAMES)[`${P}.${K}`]
  : never

/** SDK 文档与迁移提示共用的调用路径。 */
export const apiPathOf = (platform: Platform, endpoint: string): string => {
  const name = API_NAMES[`${platform}.${endpoint}` as keyof typeof API_NAMES]
  if (!name) throw new Error(`未登记公开方法名：${platform}.${endpoint}`)
  if (name.startsWith('tools.')) return name
  const channel = platform === 'douyin' ? `.${douyinChannelOf(endpoint)}` : ''
  return `client.${platform}${channel}.${name}`
}
